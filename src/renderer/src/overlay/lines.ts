let last = ''
export function pick(key: LineKey, vars: Record<string, string> = {}): string {
  const list = LINES[key] as readonly string[]
  let s = list[Math.floor(Math.random() * list.length)]
  if (list.length > 1 && s === last) s = list[(list.indexOf(s) + 1) % list.length]
  last = s
  return s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '')
}
